# ---- 画像出力 ----
xs, ys = zip(*P)
fig, ax = plt.subplots(figsize=(6, 10))
ax.add_patch(MplPolygon(P, closed=True, facecolor="#b0c4de", edgecolor="#1a3a5c", linewidth=1.2))
